def recommend_theme(
    sector: str,
    *,
    place_types: tuple[str, ...] = (),
) -> DemoTheme:
    """Recommend a trusted theme from sector text and Google place types."""

    haystack = " ".join((sector, *place_types)).casefold()
    for key, keywords in _THEME_KEYWORDS:
        if any(keyword in haystack for keyword in keywords):
            return THEMES[key]
    return THEMES[ThemeKey.GENERAL]


def resolve_theme(
    theme: ThemeKey | str | None,
    *,
    sector: str,
    place_types: tuple[str, ...] = (),
) -> DemoTheme:
    """Resolve an explicit preset or fall back to a sector recommendation."""

    if theme is None or (isinstance(theme, str) and not theme.strip()):
        return recommend_theme(sector, place_types=place_types)

    try:
        key = theme if isinstance(theme, ThemeKey) else ThemeKey(theme.strip())
    except ValueError as exc:
        raise ValueError(f"Unknown demo theme: {theme!r}") from exc
    return THEMES[key]


def render_theme_css(theme: DemoTheme) -> str:
    """Render CSS overrides from an application-owned preset only."""

    return f"""
:root {{
  --bg: {theme.background};
  --surface-strong: {theme.surface_strong};
  --line: {theme.line};
  --accent: {theme.accent};
  --accent-soft: {theme.accent_soft};
}}
.eyebrow {{ color: {theme.accent_text}; }}
.hero-panel::after {{
  background: radial-gradient(circle, {theme.glow}, rgba(0,0,0,0));
}}
.about-visual {{
  background:
    linear-gradient(145deg, {theme.surface_strong}, {theme.surface_strong}e6),
    radial-gradient(circle at 25% 20%, {theme.glow}, transparent 38%);
}}
.contact-shell .section-kicker,
.location-link {{ color: {theme.accent}; }}
""".strip()
