"""Trusted visual theme presets for generated website demos."""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum


class ThemeKey(str, Enum):
    """Stable theme identifiers stored by the demo pipeline."""

    GENERAL = "general"
    HAIR_BEAUTY = "hair_beauty"
    AUTOMOTIVE = "automotive"
    PROPERTY = "property"
    LOGISTICS = "logistics"
    EVENT = "event"
    CONSTRUCTION = "construction"


@dataclass(frozen=True, slots=True)
class DemoTheme:
    """A fixed, application-owned visual theme.

    Values are never generated by the model or accepted as arbitrary CSS from
    users. Keeping the palette and visual motif application-owned makes later
    static demo generation deterministic and safe.
    """

    key: ThemeKey
    label: str
    accent: str
    accent_soft: str
    accent_text: str
    background: str
    surface_strong: str
    line: str
    glow: str
    visual_label: str


